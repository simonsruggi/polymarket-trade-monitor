def display_trade(trade_info, is_anomalous):
    """Display a trade with rich formatting."""
    if is_anomalous:
        style = "bold red"
        title = "ANOMALOUS TRADE DETECTED"
        border_style = "red"
    else:
        style = "cyan"
        title = "Trade"
        border_style = "blue"

    trade_table = Table(box=box.SIMPLE, show_header=False, padding=(0, 1))
    trade_table.add_column("Field", style="dim")
    trade_table.add_column("Value", style=style)

    trade_table.add_row("Hash", trade_info['trade_hash'][:16] + "...")
    trade_table.add_row("Amount", f"${trade_info['amount']:,.2f}")
    trade_table.add_row("Price", f"{trade_info['price']:.4f}")
    trade_table.add_row("Size", f"{trade_info['size']:,.2f}")
    trade_table.add_row("Market", trade_info['market_title'][:50] + "..." if len(trade_info['market_title']) > 50 else trade_info['market_title'])
    trade_table.add_row("Outcome", trade_info['outcome'])
    trade_table.add_row("Side", trade_info['side'])
    trade_table.add_row("Trader", trade_info['trader'])
    trade_table.add_row("Time", trade_info['timestamp'])

    if is_anomalous:
        alert_text = Text()
        alert_text.append("Low price: ", style="yellow")
        alert_text.append(f"{trade_info['price']:.4f} <= {ANOMALY_PRICE_MAX}\n", style="white")
        alert_text.append("Large size: ", style="yellow")
        alert_text.append(f"{trade_info['size']:,.2f} >= {ANOMALY_SIZE_MIN:,}", style="white")
        console.print(Panel(
            alert_text,
            title=f"[bold red]{title}[/bold red]",
            border_style=border_style,
            box=box.HEAVY
        ))

    console.print(Panel(trade_table, border_style=border_style))


def main_loop(tracked_wallets=None, tracked_usernames=None):
    """Main monitoring loop."""
    global trade_cache_cleanup_counter

    # Display configuration
    config_table = Table(title="Active Configuration", box=box.ROUNDED, border_style="green")
    config_table.add_column("Setting", style="cyan")
    config_table.add_column("Value", style="white")

    if tracked_wallets or tracked_usernames:
        config_table.add_row("Mode", "[yellow]Tracking Mode[/yellow]")
        if tracked_wallets:
            config_table.add_row("Tracked Wallets", str(len(tracked_wallets)))
        if tracked_usernames:
            config_table.add_row("Tracked Usernames", str(len(tracked_usernames)))
    else:
        config_table.add_row("Mode", "[cyan]Large Trade Monitor[/cyan]")
        config_table.add_row("Min Trade Amount", f"${MIN_TRADE_AMOUNT:,}")

    config_table.add_row("Anomaly Criteria", f"price <= {ANOMALY_PRICE_MAX}, size >= {ANOMALY_SIZE_MIN:,}")
    config_table.add_row("Max Trade Age", f"{MAX_TRADE_AGE_MINUTES} minutes")
    config_table.add_row("Discord Webhook", "[green]Configured[/green]" if DISCORD_WEBHOOK else "[dim]Not configured[/dim]")

    console.print(config_table)
    console.print()
    console.print("[bold green]Starting monitor...[/bold green] Press Ctrl+C to stop.\n")

    while True:
        try:
            with Progress(
                SpinnerColumn(),
                TextColumn("[progress.description]{task.description}"),
                console=console,
                transient=True
            ) as progress:
                task = progress.add_task("Fetching trades...", total=None)

                if tracked_wallets or tracked_usernames:
                    trades = fetch_trades(min_amount=None)
                else:
                    trades = fetch_trades(min_amount=MIN_TRADE_AMOUNT)

            if trades:
                trade_count = len(trades)
                if tracked_wallets or tracked_usernames:
                    console.print(f"[dim]Received {trade_count} trades (no amount filter)[/dim]")
                else:
                    console.print(f"[dim]Received {trade_count} trades >= ${MIN_TRADE_AMOUNT:,}[/dim]")

                if tracked_wallets or tracked_usernames:
                    trades_to_show = trades
                else:
                    trades_to_show = trades[:10]

                new_trades_count = 0
                anomalous_trades_count = 0

                for trade in trades_to_show:
                    trade_id = trade.get("transactionHash", "unknown")
                    timestamp = trade.get("timestamp", 0)

                    trader_address = (trade.get("trader", "") or "").lower()
                    pseudonym = trade.get("pseudonym", "")

                    if tracked_wallets or tracked_usernames:
                        allowed = False
                        if tracked_wallets and trader_address in tracked_wallets:
                            allowed = True
                        if tracked_usernames and pseudonym in tracked_usernames:
                            allowed = True
                        if not allowed:
                            continue

                    trade_key = f"{trade_id}_{timestamp}"
                    if trade_key in notified_trades:
                        continue

                    if timestamp:
                        trade_time = datetime.utcfromtimestamp(timestamp)
                        time_diff = datetime.utcnow() - trade_time
                        age_minutes = time_diff.total_seconds() / 60
                        if age_minutes > MAX_TRADE_AGE_MINUTES:
                            continue

                    try:
                        trade_ts = int(timestamp) if timestamp else int(datetime.utcnow().timestamp())
                    except Exception:
                        trade_ts = int(datetime.utcnow().timestamp())
                    notified_trades[trade_key] = trade_ts

                    price = float(trade.get("price", 0))
                    size = float(trade.get("size", 0))
                    amount = price * size
                    title = trade.get("title", "Unknown Market")
                    slug = trade.get("slug", "unknown")
                    condition_id = trade.get("conditionId", "")
                    side = trade.get("side", "Unknown")
                    outcome = trade.get("outcome", "Unknown")
                    pseudonym = trade.get("pseudonym", "Anonymous")

                    if timestamp:
                        ts = datetime.utcfromtimestamp(timestamp).strftime("%Y-%m-%d %H:%M:%S")
                    else:
                        ts = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

                    is_anomalous = is_anomalous_trade(price, size, amount)
                    market_link = get_market_link(slug, condition_id)
                    trader_link = get_trader_link(pseudonym, trader_address)

                    trade_info = {
                        "trade_hash": trade_id,
                        "amount": amount,
                        "price": price,
                        "size": size,
                        "market_title": title,
                        "market_slug": slug,
                        "market_link": market_link,
                        "outcome": outcome,
                        "side": side,
                        "trader": pseudonym,
                        "trader_address": trader_address,
                        "trader_link": trader_link,
                        "timestamp": ts,
                        "is_anomalous": is_anomalous
                    }

                    display_trade(trade_info, is_anomalous)
                    save_to_csv([trade_info])
                    new_trades_count += 1

                    is_tracking_mode = bool(tracked_wallets or tracked_usernames)
                    if is_tracking_mode or is_anomalous:
                        if is_anomalous:
                            anomalous_trades_count += 1
                        if DISCORD_WEBHOOK:
                            console.print("[dim]Sending Discord notification...[/dim]")
                            send_discord_notification(trade_info)

                if new_trades_count > 0:
                    summary = Text()
                    summary.append(f"Processed {new_trades_count} new trade(s)", style="green")
                    if anomalous_trades_count > 0:
                        summary.append(f" | {anomalous_trades_count} anomalous", style="bold red")
                    console.print(summary)
                else:
                    console.print("[dim]No new trades[/dim]")
            else:
                console.print("[dim]No trades available[/dim]")

        except KeyboardInterrupt:
            console.print("\n[yellow]Monitor stopped by user.[/yellow]")
            break
        except Exception as e:
            console.print(f"[red]Error during processing:[/red] {e}")

        # Periodic cache cleanup
        trade_cache_cleanup_counter += 1
        if trade_cache_cleanup_counter >= 100:
            now_ts = int(datetime.utcnow().timestamp())
            retention_secs = int(MAX_TRADE_AGE_MINUTES * 60)
            notified_trades_keys = list(notified_trades.keys())
            for k in notified_trades_keys:
                seen_ts = notified_trades.get(k, 0)
                if seen_ts <= 0 or (now_ts - seen_ts) > retention_secs:
                    notified_trades.pop(k, None)
            trade_cache_cleanup_counter = 0

        console.print(f"[dim]Next check in {LOOP_INTERVAL}s...[/dim]\n")
        time.sleep(LOOP_INTERVAL)


def main():
    """Main entry point."""
    print_header()

    # Check if setup is needed
    if needs_setup():
        console.print("[yellow]No configuration found. Starting setup wizard...[/yellow]\n")
        setup_wizard()
    else:
        # Offer to run setup again
        console.print("[dim]Configuration loaded from .env[/dim]")
        console.print("[dim]Run with --setup to reconfigure[/dim]\n")

    # Check for --setup flag
    if "--setup" in sys.argv:
        setup_wizard()

    choice = choose_mode()

    if choice == "1":
        main_loop()
    elif choice == "2":
        existing_wallets = load_tracked_wallets()
        existing_usernames = load_tracked_usernames()

        if existing_wallets:
            console.print(f"[cyan]Found {len(existing_wallets)} existing wallet(s)[/cyan]")
        if existing_usernames:
            console.print(f"[cyan]Found {len(existing_usernames)} existing username(s)[/cyan]")
        console.print()

        raw_w = Prompt.ask(
            "[yellow]Enter wallet addresses to track[/yellow] (comma-separated, Enter to keep existing)",
            default=""
        )
        new_wallets = {w.strip().lower() for w in raw_w.split(',') if w.strip()}
        new_wallets = {w for w in new_wallets if w.startswith('0x') and len(w) == 42}

        raw_u = Prompt.ask(
            "[yellow]Enter Polymarket usernames to track[/yellow] (comma-separated, Enter to keep existing)",
            default=""
        )
        new_usernames = {u.strip() for u in raw_u.split(',') if u.strip()}

        tracked_wallets = set(existing_wallets)
        tracked_wallets.update(new_wallets)
        tracked_usernames = set(existing_usernames)
        tracked_usernames.update(new_usernames)

        if new_wallets:
            save_tracked_wallets(tracked_wallets)
        if new_usernames:
            save_tracked_usernames(tracked_usernames)

        if not tracked_wallets and not tracked_usernames:
            console.print("[yellow]No wallets or usernames to track. Exiting.[/yellow]")
        else:
            console.print()
            main_loop(tracked_wallets=tracked_wallets, tracked_usernames=tracked_usernames)
    else:
        console.print("[cyan]Goodbye![/cyan]")


if __name__ == "__main__":
    main()
