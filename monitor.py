def send_discord_notification(trade):
    """Send a Discord notification for a trade."""
    try:
        if not DISCORD_WEBHOOK or DISCORD_WEBHOOK == "":
            return

        trader_stats = get_trader_stats(trade.get('trader_address', ''))
        is_anomalous = bool(trade.get('is_anomalous', False))

        if is_anomalous:
            description = (
                f"**ALERT: Low price + Large size!**\n\n"
                f"**Market:** {trade['market_title']}\n"
                f"**Amount:** ${trade['amount']:,.2f}\n"
                f"**Price:** {trade['price']:.4f} (<= {ANOMALY_PRICE_MAX})\n"
                f"**Size:** {trade['size']:,.2f} (>= {ANOMALY_SIZE_MIN:,})\n"
                f"**Outcome:** {trade['outcome']}\n"
                f"**Side:** {trade['side']}\n"
                f"**Trader:** {trade['trader']}\n"
                f"**Time:** {trade['timestamp']}\n\n"
            )
        else:
            description = (
                f"**Market:** {trade['market_title']}\n"
                f"**Amount:** ${trade['amount']:,.2f}\n"
                f"**Price:** {trade['price']:.4f}\n"
                f"**Size:** {trade['size']:,.2f}\n"
                f"**Outcome:** {trade['outcome']}\n"
                f"**Side:** {trade['side']}\n"
                f"**Trader:** {trade['trader']}\n"
                f"**Time:** {trade['timestamp']}\n\n"
            )

        if trader_stats:
            description += (
                f"**TRADER INFO:**\n"
                f"Markets Traded: {trader_stats['total_markets']}\n"
                f"Wallet: `{trader_stats['trader_address'][:10]}...{trader_stats['trader_address'][-6:]}`\n\n"
            )

        description += (
            f"[Trade ->]({trade['market_link']})\n"
            f"[Trader Profile ->]({trade['trader_link']})"
        )

        if is_anomalous:
            embed = {
                "title": f"ANOMALOUS TRADE: ${trade['amount']:,.2f}",
                "description": description,
                "color": 15158332  # red
            }
        else:
            embed = {
                "title": f"Trade update: ${trade['amount']:,.2f}",
                "description": description,
                "color": 3447003  # blue
            }

        payload = {"username": "Polymarket Monitor", "embeds": [embed]}
        requests.post(DISCORD_WEBHOOK, json=payload, timeout=10)
    except Exception as e:
        console.print(f"[red]Error sending Discord notification:[/red] {e}")


def save_to_csv(data):
    """Append results to CSV file."""
    if not data:
        return
    with open(CSV_OUTPUT, "a", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=data[0].keys())
        if f.tell() == 0:
            writer.writeheader()
        writer.writerows(data)


def is_anomalous_trade(price, size, amount):
    """Check if a trade is anomalous based on low price and large size."""
    return (price <= ANOMALY_PRICE_MAX and
            size >= ANOMALY_SIZE_MIN and
            amount >= ANOMALY_AMOUNT_MIN)


def get_market_link(slug, condition_id):
    """Generate the correct market link on Polymarket."""
    if slug and slug != "unknown":
        return f"https://polymarket.com/market/{slug}"
    elif condition_id:
        return f"https://polymarket.com/market/{condition_id}"
    else:
        return "https://polymarket.com"


def get_trader_link(pseudonym, trader_address=None):
    """Generate the link to the trader profile on Polymarket."""
    if (trader_address and
        trader_address != "unknown" and
        trader_address != "" and
        trader_address.startswith("0x")):
        return f"https://polymarket.com/profile/{trader_address}"
    else:
        return f"Trader: {pseudonym} (address not available)"


def get_trader_stats(trader_address):
    """Fetch basic trader stats from Polymarket's API."""
    try:
        if not trader_address or trader_address == "unknown":
            return None

        url = f"https://data-api.polymarket.com/traded/{trader_address}"
        response = requests.get(url, timeout=5)

        if response.status_code == 200:
            data = response.json()
            total_markets = data.get('totalMarkets', 0)

            return {
                'total_markets': total_markets,
                'trader_address': trader_address
            }
    except Exception:
        pass
    return None


def fetch_trades(min_amount=None):
    """Fetch trades from Polymarket API."""
    try:
        params = {}
        if min_amount is not None:
            params = {
                'filterType': 'CASH',
                'filterAmount': min_amount
            }
        response = requests.get("https://data-api.polymarket.com/trades", params=params, timeout=10)
        response.raise_for_status()
        return response.json()
    except Exception as e:
        console.print(f"[red]Error fetching trades:[/red] {e}")
        return []


def load_tracked_wallets():
    """Load tracked wallets from disk as a lowercase set."""
    if not os.path.exists(TRACKED_WALLETS_FILE):
        return set()
    wallets = set()
    try:
        with open(TRACKED_WALLETS_FILE, "r") as f:
            for line in f:
                w = line.strip()
                if w:
                    wallets.add(w.lower())
    except Exception as e:
        console.print(f"[yellow]Warning: Error loading tracked wallets file:[/yellow] {e}")
    return wallets


def load_tracked_usernames():
    """Load tracked Polymarket usernames as case-sensitive set."""
    if not os.path.exists(TRACKED_USERNAMES_FILE):
        return set()
    names = set()
    try:
        with open(TRACKED_USERNAMES_FILE, "r") as f:
            for line in f:
                n = line.strip()
                if n:
                    names.add(n)
    except Exception as e:
        console.print(f"[yellow]Warning: Error loading tracked usernames file:[/yellow] {e}")
    return names


def save_tracked_wallets(wallets):
    """Persist tracked wallets to disk."""
    try:
        with open(TRACKED_WALLETS_FILE, "w") as f:
            for w in sorted({w.lower() for w in wallets}):
                f.write(w + "\n")
        console.print(f"[green]Saved {len(wallets)} wallet(s) to {TRACKED_WALLETS_FILE}[/green]")
    except Exception as e:
        console.print(f"[red]Error saving tracked wallets:[/red] {e}")


def save_tracked_usernames(usernames):
    """Persist tracked usernames to disk."""
    try:
        with open(TRACKED_USERNAMES_FILE, "w") as f:
            for n in sorted(set(usernames)):
                f.write(n + "\n")
        console.print(f"[green]Saved {len(usernames)} username(s) to {TRACKED_USERNAMES_FILE}[/green]")
    except Exception as e:
        console.print(f"[red]Error saving tracked usernames:[/red] {e}")


